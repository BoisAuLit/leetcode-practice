"""LC-0525 - Contiguous Array

Level 1 · 03 Prefix Sum 与 Prefix-Suffix —— 前缀状态 + 第一次出现的位置
题目在问：01 数组里，0 和 1 数量相等的最长连续子数组有多长

核心观察：把 0 看成 -1，「0 和 1 一样多」就等价于「这段的和 = 0」，
      而「区间和 = 0」等价于「两端的前缀和相等」：`pre[j] - pre[i] == 0`。

不变量：扫到下标 j 时，`first[s]` 记录前缀和第一次等于 s 的位置。
      因为要**最长**，同一个前缀和只保留最早的那次，后面再遇到就只查不写。

和同层另外两题的区别（必须分得清）：
  - 560 子数组和为 k：问**有几个**，所以哈希表存前缀和的**出现次数**，边扫边累加
  - 525 本题：问**最长**，所以哈希表存前缀和**第一次出现的下标**，只写一次
  - 974 能被 K 整除：问个数，键换成前缀和的**余数**，存次数
  三题都是「前缀状态 + 哈希表」，但存什么、什么时候写，完全不同。

坑：
  - `first[0] = -1` 这个哨兵必须有，否则从下标 0 开始的整段会被漏掉
  - 只在键不存在时才写入，写成无条件覆盖就变成求最短了
"""

from typing import List


##################################################################################################
##### ! Solution 1: 0 换成 -1，前缀和 + 第一次出现的下标
##### ! 时间复杂度: O(n)   空间复杂度: O(n)
##### ! 适用：所有「最长的、满足某个前缀状态相等的区间」；1371、1915 都是同一个壳
##### ! ⭐️⭐️⭐️⭐️⭐️ Preferred Solution
##################################################################################################


class Solution_1:
    def findMaxLength(self, nums: List[int]) -> int:
        first = {0: -1}  # ! 哨兵：前缀和 0 在「还没开始」的位置就出现过
        best = pre = 0
        for i, x in enumerate(nums):
            pre += 1 if x == 1 else -1  # ! 0 记作 -1
            if pre in first:
                best = max(best, i - first[pre])  # ! 两端前缀和相等 → 中间这段和为 0
            else:
                first[pre] = i  # ! 只记第一次，这样算出来的区间才最长
        return best


##################################################################################################
##### ! Solution 2: 暴力枚举所有区间（基线）
##### ! 时间复杂度: O(n^2)   空间复杂度: O(1)
##### ! 适用：n 很小时的对拍参照；写一遍能看清「前缀和把两重循环压成一重」省在哪
##################################################################################################


class Solution_2:
    def findMaxLength(self, nums: List[int]) -> int:
        best = 0
        for i in range(len(nums)):
            bal = 0
            for j in range(i, len(nums)):
                bal += 1 if nums[j] == 1 else -1
                if bal == 0:
                    best = max(best, j - i + 1)
        return best


if __name__ == "__main__":
    cases = [([0, 1], 2), ([0, 1, 0], 2), ([0, 1, 1, 1, 1, 1, 0, 0, 0], 6),
             ([1, 1, 1], 0), ([0, 0, 1, 0, 0, 0, 1, 1], 6)]
    for sol in (Solution_1(), Solution_2()):
        for nums, want in cases:
            got = sol.findMaxLength(nums[:])
            assert got == want, f"{type(sol).__name__} {nums}: got {got}, want {want}"
    print("2 个解法全过")
