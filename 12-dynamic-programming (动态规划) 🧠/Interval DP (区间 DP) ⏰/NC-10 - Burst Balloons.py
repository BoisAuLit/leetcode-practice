"""
📌 信号→模式: 消除元素且得分依赖左右邻居 → 区间 DP：枚举"最后被扎的" k，让它当墙劈开区间
📅 首次: 2026-09-06 | 卡点: 正着想会粘邻居、子问题耦合；必须倒过来问"谁最后死" | 守卫: [5]->5, [3,1,5,8]->167, [4,2,3,7]->143
🔁 复习: 未排期
"""
from functools import lru_cache
from typing import List


class Solution:
    # ============================================================
    # 灵魂：为什么必须问"最后扎谁"，而不能问"先扎谁"
    # ------------------------------------------------------------
    # 正着想（先扎谁）：扎掉一个气球后，它左右两边会变成新邻居
    #   [4,2,3,7] 扎掉 2 → 4 和 3 贴在一起。
    #   ⇒ 左半边的操作会改变右半边的邻居关系，两半不独立，无法拆子问题。死路。
    #
    # 倒着想（最后扎谁）：假设 k 是区间里最后一个被扎的，那么扎 k 的那一刻——
    #   ① 区间内其他气球全没了，k 的邻居恰好是区间外的两堵墙 l 和 r（固定不变！）
    #        得分 = vals[l] * vals[k] * vals[r]   ← 三个数全部确定
    #   ② k 在死之前一直站着，像一堵墙，隔开左右两堆
    #        ⇒ 左半区间和右半区间彻底独立，各自随便扎，互不干扰。活路。
    #
    # 这就是区间 DP 的标志手法：枚举"最后发生的事件"，让它把区间劈成两个独立子区间。
    # 专挑"最后"而不是"第一"，是因为最后一步发生时环境最干净（别人都死光，邻居就是墙）。
    #
    # 状态定义（开区间！）：
    #   dp(l, r) = 只扎开区间 (l, r) 内的所有气球（不含 l、r 本身）能得的最多硬币；
    #              前提是 l 和 r 这两个气球还活着，它们只当乘数、不归这个子问题扎。
    # 两端垫 1：题目说越界按 1 算，干脆真的塞进数组，省掉所有边界判断。
    # 答案 = dp(0, N-1)，两堵墙就是垫进去的那两个 1。
    #
    # 复杂度：状态 O(n²)，每个状态枚举 O(n) 个 k → O(n³)。n=300 约 2700 万次，可过。
    # ============================================================

    # ------------------------------------------------------------
    # 解法一：记忆化递归（主力版本）
    # ------------------------------------------------------------
    def maxCoins(self, nums: List[int]) -> int:
        vals = [1] + nums + [1]

        @lru_cache(maxsize=None)
        def dp(l: int, r: int) -> int:
            if r - l <= 1:                       # 开区间是空的，没气球可扎
                return 0
            best = 0
            for k in range(l + 1, r):            # 枚举：谁是这个区间里最后被扎的
                best = max(
                    best,
                    dp(l, k)                     # 先扎光 k 左边那堆（墙是 l 和还活着的 k）
                    + dp(k, r)                   # 再扎光 k 右边那堆（墙是还活着的 k 和 r）
                    + vals[l] * vals[k] * vals[r]  # 最后扎 k，此刻邻居恰是 l 和 r
                )
            return best

        return dp(0, len(vals) - 1)

    # ------------------------------------------------------------
    # 解法二：迭代（由解法一按四步配方机械翻译）—— 推荐记这版
    #   ① cache 键 (l, r) → N x N 数组，N = n + 2
    #   ② base case r-l<=1 → 0：数组本来就是全 0，白送，什么都不用做
    #   ③ dp(l,k) → dp[l][k]；dp(k,r) → dp[k][r]；return → 写 dp[l][r]
    #   ④ 循环方向 = "被读的先算"，逐维度判断：
    #        · l 这一维：读 dp[k][r] 且 k > l → 读的是更大的 l → l 倒序
    #        · r 这一维：读 dp[l][k] 且 k < r → 读的是更小的 r → r 正序
    #      （一倒一正，正是配方自己算出来的，不用背）
    """
            r=0   r=1   r=2   r=3   r=4   r=5
    l=0     .     .     .     .     .     .
    l=1     .     .     ←     ←     ★     .
    l=2     .     .     .     .     ↓     .
    l=3     .     .     .     .     ↓     .
    l=4     .     .     .     .     .     .
    l=5     .     .     .     .     .     .

    dp[l][r] = dp[l][k] + dp[k][r]
    计算某一个格子的时候, 它下面的和左面的都必须要计算出来,
    所以 l 是倒序的, r 是正序的
    k 的顺序无所谓, 但是如果是正序的话比较好算
    """
    def maxCoins_iter(self, nums: List[int]) -> int:
        vals = [1] + nums + [1]
        N = len(vals)
        dp = [[0] * N for _ in range(N)]         # base case 已含在初始值 0 里

        for l in range(N - 3, -1, -1):           # l 倒序
            for r in range(l + 2, N):            # r 正序；l+2 起步保证区间非空
                best = 0
                for k in range(l + 1, r):
                    best = max(
                        best,
                        dp[l][k] + dp[k][r] + vals[l] * vals[k] * vals[r]
                    )
                dp[l][r] = best

        return dp[0][N - 1]
