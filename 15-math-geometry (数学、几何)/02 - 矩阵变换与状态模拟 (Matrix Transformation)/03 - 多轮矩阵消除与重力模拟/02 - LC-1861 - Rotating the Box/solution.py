"""LC-1861 - Rotating the Box     ★ 第二轮审核新增（Rotation + Gravity 两个模板的交汇点）

Level 1 · 02 矩阵变换与状态模拟 —— **先重力沉降，后旋转（顺序是关键）**
题目在问：`box[i][j]` 是 `'#'`（石头）、`'*'`（固定障碍）或 `'.'`（空）。
         把盒子**顺时针旋转 90°**，然后让石头在重力作用下下落，返回最终状态。

### 决定性观察：**不要先旋转再模拟重力 —— 要先模拟重力再旋转**

旋转 90° 后「向下」对应原矩阵里的「**向右**」。
所以：

```
① 在原矩阵里，让每一行的石头往右沉（被 '*' 挡住）
② 再把整个矩阵顺时针旋转 90°
```

**为什么这个顺序更好？**
- 先旋转的话，重力方向变成了「列方向向下」，要按列遍历，还要处理
  旋转后的索引映射 —— **两件事缠在一起，容易写错**。
- 先沉降的话，每一行是**独立的一维问题**（石头往右滑到底），
  而旋转是**纯坐标变换**。**两件事解耦。**

> **这就是本题的全部价值**：把一个「旋转 + 重力」的复合问题
> 拆成两个各自已经会做的子问题。

### ① 行内重力：双指针从右往左

```python
write = n - 1                      # ! 下一个石头该落在哪
for read in range(n - 1, -1, -1):  # ! 从右往左扫
    if box[r][read] == '*':
        write = read - 1           # ! 障碍：重置落点到它左边
    elif box[r][read] == '#':
        box[r][read] = '.'         # ! 先把石头从原位拿走
        box[r][write] = '#'        # ! 再放到落点
        write -= 1
```

**为什么 `write` 遇到 `'*'` 要重置成 `read - 1`？**
`'*'` 是固定的，石头不能穿过它 ⟹ 它右边的那一段已经结算完毕，
后续（更靠左的）石头只能堆在 `'*'` 的**左侧**。

**为什么要先置 `'.'` 再写 `'#'`？**
当 `read == write`（石头本来就在落点上）时，顺序写反会变成
先写 `'#'` 再被置成 `'.'` ⟹ **石头凭空消失**。
这是本题最容易写出的 bug（见测试里 `[["#"]]` 这类用例）。
> 和 [LC-0289 Game of Life](<../../02 - 原地标记与同步状态更新/02 - LC-0289 - Game of Life>)
> 的「读旧写新」是同一类问题：**原地修改时，写入顺序决定正确性。**

### ② 顺时针旋转 90°：`(r, c) → (c, m-1-r)`

`m × n` 的矩阵旋转后变成 `n × m`：

```python
rotated = [[box[m - 1 - c][r] for c in range(m)] for r in range(n)]
```
（新矩阵第 `r` 行第 `c` 列 = 原矩阵第 `m-1-c` 行第 `r` 列）

**和 [LC-0048 Rotate Image](<../../01 - 转置与矩阵旋转/02 - LC-0048 - Rotate Image>) 的区别**：
LC-0048 是**正方形**矩阵，可以**原地**旋转（转置 + 翻转每一行）；
本题是 `m × n` **矩形**，旋转后形状都变了（`n × m`）⟹ **必须开新矩阵**，
这和 [LC-0867 Transpose Matrix](<../../01 - 转置与矩阵旋转/01 - LC-0867 - Transpose Matrix>)
不要求原地是同一个理由。

**验证旋转公式的小技巧**：拿 `[[1,2],[3,4]]` 试一下，顺时针 90° 应得 `[[3,1],[4,2]]`
—— 原来的第一列 `(1,3)` 变成了第一行 `(3,1)`（**倒序**）。
即「**原矩阵的列，从下往上读，变成新矩阵的行**」。

### 和 LC-0723 Candy Crush 的对比

| | [LC-0723 Candy Crush](<../01 - LC-0723 - Candy Crush>) | **LC-1861** 本题 |
|---|---|---|
| 重力方向 | 向下（按列） | 原矩阵里向右（按行），旋转后才是向下 |
| 轮数 | **反复多轮**直到稳定 | **一轮**就结束 |
| 有障碍吗 | ❌ | ✅ `'*'` 把每行切成多段 |
| 核心 | 标记消除 + 重力 + 循环 | 重力 + 旋转，解耦成两步 |

复杂度：**O(m·n)** 时间（一遍沉降 + 一遍旋转）、
       **O(m·n)** 空间（旋转后形状变化，必须开新矩阵）。

边界：
  - 单个石头 `[["#"]]` → `[["#"]]`（写入顺序的试金石）
  - 没有石头 `[["."]]` / 全是 `'*'`
  - 石头已经在最右端（`read == write`）
  - 障碍把一行切成多段 `[["#","*","#"]]`
  - 1×n（单行）和 n×1（单列）
  - 石头在障碍左侧，不能穿过
"""

from typing import List


##################################################################################################
##### ! Solution 1: 先行内双指针沉降（往右），再顺时针旋转 90°
##### ! 时间复杂度: O(m·n)   空间复杂度: O(m·n)（旋转后是 n×m，必须新建）
##### ! 适用：所有「旋转 + 重力」复合题。关键是先沉降后旋转，把两件事解耦
##### ! ⭐️⭐️⭐️⭐️⭐️ Preferred Solution
##################################################################################################


class Solution_1:
    def rotateTheBox(self, box: List[List[str]]) -> List[List[str]]:
        m, n = len(box), len(box[0])
        # ! ① 在原矩阵里让石头往右沉（旋转后的「向下」就是现在的「向右」）
        for r in range(m):
            write = n - 1                       # ! 下一个石头的落点
            for read in range(n - 1, -1, -1):
                if box[r][read] == "*":
                    write = read - 1            # ! 障碍不可穿越 ⟹ 落点重置到它左边
                elif box[r][read] == "#":
                    box[r][read] = "."          # ! 必须先拿走，再放下
                    box[r][write] = "#"         # ! read == write 时顺序写反会让石头消失
                    write -= 1
        # ! ② 顺时针旋转 90°：新 [r][c] = 原 [m-1-c][r]
        return [[box[m - 1 - c][r] for c in range(m)] for r in range(n)]


##################################################################################################
##### ! Solution 2: 先旋转，再按列向下沉降（直译题意，但索引更绕）
##### ! 时间复杂度: O(m·n)   空间复杂度: O(m·n)
##### ! 适用：对照用。能跑对，但「按列遍历 + 旋转后索引」两件事缠在一起，更容易写错
##################################################################################################


class Solution_2:
    def rotateTheBox(self, box: List[List[str]]) -> List[List[str]]:
        m, n = len(box), len(box[0])
        g = [[box[m - 1 - c][r] for c in range(m)] for r in range(n)]   # ! 先旋转，得到 n×m
        rows, cols = n, m
        for c in range(cols):
            write = rows - 1                    # ! 这一列里石头的落点（最底部）
            for read in range(rows - 1, -1, -1):
                if g[read][c] == "*":
                    write = read - 1
                elif g[read][c] == "#":
                    g[read][c] = "."
                    g[write][c] = "#"
                    write -= 1
        return g


##################################################################################################
##### ! Solution 3: 暴力基准（逐段切分 + 重排，用于对拍）
##### ! 时间复杂度: O(m·n)   空间复杂度: O(m·n)
##### ! 适用：仅用于对拍。把每行按 '*' 切段，段内「石头靠右、空格靠左」重排
##################################################################################################


class Solution_3:
    def rotateTheBox(self, box: List[List[str]]) -> List[List[str]]:
        m, n = len(box), len(box[0])
        g = [row[:] for row in box]
        for r in range(m):
            # ! 按 '*' 把这一行切成若干段，每段内部独立结算
            seg_start = 0
            for c in range(n + 1):
                if c == n or g[r][c] == "*":
                    stones = sum(1 for k in range(seg_start, c) if g[r][k] == "#")
                    length = c - seg_start
                    for k in range(seg_start, c):
                        # ! 段内靠右的 stones 格放石头，其余放 '.'
                        g[r][k] = "#" if k >= c - stones else "."
                    assert length >= 0
                    seg_start = c + 1
        return [[g[m - 1 - c][r] for c in range(m)] for r in range(n)]


if __name__ == "__main__":
    import random

    for cls in (Solution_1, Solution_2, Solution_3):
        s = cls()
        assert s.rotateTheBox([["#", ".", "#"]]) == [["."], ["#"], ["#"]]
        assert s.rotateTheBox([["#", ".", "*", "."], ["#", "#", "*", "."]]) == [
            ["#", "."], ["#", "#"], ["*", "*"], [".", "."],
        ]
        assert s.rotateTheBox(
            [["#", "#", "*", ".", "*", "."],
             ["#", "#", "#", "*", ".", "."],
             ["#", "#", "#", ".", "#", "."]]
        ) == [
            [".", "#", "#"], [".", "#", "#"], ["#", "#", "*"],
            ["#", "*", "."], ["#", ".", "*"], ["#", ".", "."],
        ]
        assert s.rotateTheBox([["#"]]) == [["#"]]           # ! read == write 的试金石
        assert s.rotateTheBox([["."]]) == [["."]]
        assert s.rotateTheBox([["*"]]) == [["*"]]
        assert s.rotateTheBox([["#", "*", "#"]]) == [["#"], ["*"], ["#"]]   # ! 障碍切成两段
        assert s.rotateTheBox([["#"], ["#"], ["."]]) == [[".", "#", "#"]]   # ! n×1

    print('[["#",".","*","."],["#","#","*","."]] ->')
    for row in Solution_1().rotateTheBox([["#", ".", "*", "."], ["#", "#", "*", "."]]):
        print("   ", row)

    for _ in range(800):                        # ! 随机对拍
        m, n = random.randint(1, 5), random.randint(1, 5)
        b = [[random.choice("#*.") for _ in range(n)] for _ in range(m)]
        o1 = Solution_1().rotateTheBox([r[:] for r in b])
        o2 = Solution_2().rotateTheBox([r[:] for r in b])
        o3 = Solution_3().rotateTheBox([r[:] for r in b])
        assert o1 == o2 == o3, (b, o1, o2, o3)
    print("随机对拍 800 组通过 ✓（先沉降后旋转 == 先旋转后沉降 == 分段重排暴力）")
