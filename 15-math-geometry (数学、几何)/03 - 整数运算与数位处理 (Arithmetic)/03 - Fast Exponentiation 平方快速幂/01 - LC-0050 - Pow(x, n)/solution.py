"""LC-0050 - Pow(x, n)

Level 1 · 03 整数运算与数位处理 → Level 2 · 03 Fast Exponentiation 平方快速幂

题目在问：实现 `pow(x, n)`，`n` 可以是负数（`-2^31 <= n <= 2^31 - 1`）。

### 核心观察：指数折半

```
n 是偶数：  x^n = (x·x)^(n/2)
n 是奇数：  x^n = x · x^(n-1)
```

每一步都把指数**至少减半** ⟹ 循环次数是 `|n|` 的二进制位数 ⟹ **O(log |n|)**。
`|n| <= 2^31` ⟹ 最多 31 轮。对比朴素的 `n` 次乘法（`2^31 ≈ 21 亿` 次），
这是从「几十亿」降到「31」—— 这就是 `Solution_3` 必定超时、而 `Solution_2` 瞬间返回的原因。

### 为什么「处理指数的二进制位」等于「把 x^n 拆成若干平方项的乘积」

把 `n` 写成二进制 `n = Σ bᵢ·2^i`（`bᵢ ∈ {0,1}`），于是

```
x^n = x^(Σ bᵢ·2^i) = Π (x^(2^i))^bᵢ
```

即 **`x^n` 等于「那些 `bᵢ = 1` 对应的 `x^(2^i)` 的乘积」**。
迭代版里的 `base` 每轮自乘一次，第 `i` 轮恰好是 `x^(2^i)`
⟹ `if n & 1: result *= base` 就是「把这一项选进乘积」。

`x^13`，`13 = 1101₂ = 8 + 4 + 1`：

| 轮 | `n`（二进制） | `n & 1` | `base` | `result` |
|---|---|---|---|---|
| 0 | `1101` | 1 ✅ | `x^1` | `x^1` |
| 1 | `110` | 0 | `x^2` | `x^1` |
| 2 | `11` | 1 ✅ | `x^4` | `x^5` |
| 3 | `1` | 1 ✅ | `x^8` | `x^13` ✓ |

### 负指数：符号在门外处理恰好一次

`x^(-n) = 1 / x^n = (1/x)^n`。把符号**提到循环外面**处理一次，
循环体里就不需要任何负数分支 —— 这是 note.md 里反复记的那一条。

> ⚠️ **C++ / Java 的额外坑**：`n == INT_MIN == -2^31` 时 `-n` **会溢出**
> （`2^31` 放不进 `int`）。必须先转 `long`，或单独特判这个值。
> **Python 整数任意精度，不受影响** —— 但面试写 C++ 时一定要主动提这一点。

### 边界

| 情况 | 期望 | 为什么容易错 |
|---|---|---|
| `n == 0` | **1.0**（任何 `x`，含 `x == 0`） | 循环一次都不进，`result` 初值必须是 `1.0` |
| `n < 0` | `1 / x^|n|` | 忘记取倒数 |
| `x == -1` | `n` 偶 → 1.0，`n` 奇 → -1.0 | 快速幂天然正确，不必特判 |
| `x == 0, n > 0` | 0.0 | — |
| `x == 0, n < 0` | 数学上未定义 | 题目约束保证不出现 |
| `n == -2^31` | 要能算 | C++/Java 的溢出点 |

**浮点误差（这里有个容易被当成 bug 的真相）**：快速幂只做 O(log n) 次乘法，
误差累积远小于朴素的 O(n) 次连乘 —— 它不仅更快，精度也更好。
但**误差不可能做到 1e-9 以内**：`x^n` 对 `x` 的条件数就是 `n`，
所以任何方法的相对误差都是 **O(n·ε)**（`ε ≈ 2.2e-16`）。实测：

| `n` | 迭代快速幂 vs Python 内置 `x ** n` 的相对误差 |
|---|---|
| 10 | 0（恰好相等） |
| 1 000 | 5.8e-15 |
| 10⁶ | 5.6e-12 |
| 10⁹ | 5.6e-9 |
| 2³¹ − 1 | **1.2e-8** |

⟹ 别指望 `myPow(2.0, 10) == 1024.0` 严格成立，更别用固定的 `1e-9` 去卡大指数。
下面 driver 里的容差写成 `1e-9 + |n|·2.3e-16`，正是这条 O(n·ε) 上界。
LeetCode 自己的判题容差是 `1e-5`，也是同一个道理。

### 四种实现

| | 解法 | 时间 | 空间 |
|---|---|---|---|
| `Solution` | 递归折半（原有代码） | O(log n) | O(log n) 递归栈 |
| `Solution_2` ⭐️ | 迭代二进制快速幂 | O(log n) | O(1) |
| `Solution_3` | 朴素连乘（反面教材） | O(n) | O(1) |
| `_pow_mod` | 同一骨架换成模乘（迁移示例） | O(log n) | O(1) |

### 和本专题其他数位题的关系

| 题 | 共享什么 | 不同点 |
|---|---|---|
| LC-0066 Plus One | 逐位取出 → 做点事 → 合并 | 处理**十进制**位 + 进位 |
| LC-0007 Reverse Integer | 逐位取出 → 做点事 → 合并 | 处理**十进制**位 + 32 位溢出判断 |
| **LC-0050** 本题 | 逐位取出 → 做点事 → 合并 | 处理**二进制**位，而且每位对应一个**平方项** |

> 三题是同一个骨架。LC-0050 的特别之处：位的权重不是 `10^i`，而是「自乘 i 次」。

### 这个骨架迁移到哪里（都只需换掉「乘法」的定义）

| 迁移 | 把 `*` 换成 | 用途 |
|---|---|---|
| **Modular Exponentiation** | `(a * b) % MOD` | 大数取模幂、RSA、组合数 |
| **Matrix Exponentiation** | 矩阵乘法 | O(log n) 求线性递推第 n 项 |
| **Binary Lifting** | 「跳 2^k 步」的合成 | 树上 LCA、倍增求祖先 |

> 骨架完全一样：`while n: if n & 1: res = res ⊗ base; base = base ⊗ base; n >>= 1`。
> 只要 `⊗` 满足**结合律**，这个模板就成立 —— 一个模板，一串题。
"""


##################################################################################################
##### ! Solution 1: 递归折半（= 下面的 class Solution，用户原有代码，未改动）
##### ! 时间复杂度: O(log n)   空间复杂度: O(log n)（递归栈，深度 <= 31）
##### ! 适用：最容易在白板上推导的形态 —— half = f(k//2) 只算一次，奇数补一个 x。
#####         符号在 dfs 外面处理，函数内部只认非负指数（职责单一）
##################################################################################################


class Solution:
    def myPow(self, x: float, n: int) -> float:
        def fast(x: float, k: int) -> float:
            # 计算 x^k,k >= 0
            if k == 0:
                return 1.0  # 任何数的 0 次方是 1
            half = fast(x, k // 2)  # 先解决一半
            if k % 2 == 1:
                return half * half * x  # 奇数:平方后补上零头的一个 x
            return half * half  # 偶数:平方即可

        res = fast(x, abs(n))
        return res if n >= 0 else 1 / res  # 负指数:最后取一次倒数


##################################################################################################
##### ! Solution 2: 迭代二进制快速幂（无递归栈，常数更小）
##### ! 时间复杂度: O(log n)   空间复杂度: O(1)
##### ! 适用：面试首选，也是可以直接迁移到模幂 / 矩阵幂 / 倍增的那个骨架。
#####         按 |n| 的二进制位走：遇到 1 就把当前的 x^(2^i) 乘进答案
##### ! ⭐️⭐️⭐️⭐️⭐️ Preferred Solution
##################################################################################################


class Solution_2:
    def myPow(self, x: float, n: int) -> float:
        if n < 0:                   # ! 符号在循环外面处理恰好一次
            x = 1 / x
            n = -n                  # ! Python 整数任意精度；C++ 里这行在 n == INT_MIN 会溢出
        result = 1.0                # ! n == 0 时直接返回 1.0，所以初值必须是 1.0
        base = x
        while n:
            if n & 1:               # ! 当前最低位是 1 ⟹ 把这一项选进乘积
                result *= base
            base *= base            # ! 第 i 轮的 base 恰好是 x^(2^i)
            n >>= 1
        return result


##################################################################################################
##### ! Solution 3: 朴素连乘（反面教材，note.md 里点名的「疤痕」）
##### ! 时间复杂度: O(n) —— n 可达 2^31 ⟹ 约 21 亿次乘法 ⟹ **必定超时**
##### ! 空间复杂度: O(1)
##### ! 适用：仅用于对照。保留它是为了记住 (1.0000001, 2147483647) 这组守卫：
#####         Solution_2 瞬间返回，这一版要跑到天荒地老。下面的 driver 只敢用小 n 测它
##################################################################################################


class Solution_3:
    def myPow(self, x: float, n: int) -> float:
        k = abs(n)
        result = 1.0
        for _ in range(k):          # ! 一次只把指数减 1（对比快速幂的「每次减半」）
            result *= x
        return result if n >= 0 else 1 / result


##################################################################################################
##### ! 迁移示例: 同一个骨架，把「乘法」换成「模乘」⟹ Modular Exponentiation
##### ! 时间复杂度: O(log e)   空间复杂度: O(1)
##### ! 适用：组合数取模、RSA、哈希。和 Solution_2 逐行对照着看 ——
#####         唯一的差别是 res = res ⊗ base 里的 ⊗ 从 `*` 变成了 `(a * b) % mod`。
#####         只要 ⊗ 满足结合律，这个 while 骨架就成立（矩阵幂、倍增同理）
##################################################################################################


def _pow_mod(base: int, exp: int, mod: int) -> int:
    result = 1
    base %= mod
    while exp:
        if exp & 1:
            result = result * base % mod    # ! ⊗ 换成了模乘
        base = base * base % mod
        exp >>= 1
    return result


if __name__ == "__main__":
    import math
    import random
    import time

    IMPLS = [Solution, Solution_2]           # ! Solution_3 是 O(n)，只在小 n 上参与

    def close(a: float, b: float, n: int = 0) -> bool:
        # ! 容差随 |n| 放大：x^n 对 x 的条件数就是 n ⟹ 相对误差天然是 O(n·ε)。
        # ! 实测 n = 2^31 - 1 时迭代版与 Python 内置 x**n 相差 1.2e-8 —— 这不是 bug，
        # ! 是浮点的硬下限（LeetCode 自己的判题容差也正是 1e-5）。
        tol = 1e-9 + abs(n) * 2.3e-16
        return abs(a - b) <= tol * max(1.0, abs(a), abs(b))

    # ! 官方样例 + note.md 里的四个守卫
    CASES = [
        (2.0, 10, 1024.0),                   # ! 官方样例 1
        (2.1, 3, 9.261000000000001),         # ! 官方样例 2
        (2.0, -2, 0.25),                     # ! 官方样例 3：负指数
        (2.0, -3, 0.125),                    # ! 守卫：负指数
        (2.0, 0, 1.0),                       # ! 守卫：零指数
        (0.0, 5, 0.0),                       # ! 守卫：零底数
        (1.0, -2147483648, 1.0),             # ! 守卫：C++/Java 的 -n 溢出点
        (-1.0, 3, -1.0),                     # ! 负底数奇次幂
        (-1.0, 4, 1.0),                      # ! 负底数偶次幂
        (0.5, 2, 0.25),
    ]
    for x, n, want in CASES:
        for cls in IMPLS:
            got = cls().myPow(x, n)
            assert close(got, want, n), (cls.__name__, x, n, got, want)
        if abs(n) <= 1000:                   # ! 朴素版只敢喂小指数
            assert close(Solution_3().myPow(x, n), want, n), (x, n)

    # ! 守卫：(1.0000001, 2147483647) 必须「瞬间」返回 —— 专杀 O(n) 版
    t0 = time.perf_counter()
    big = Solution_2().myPow(1.0000001, 2147483647)
    elapsed = time.perf_counter() - t0
    assert elapsed < 0.01, f"快速幂不该慢：{elapsed:.4f}s"
    assert close(big, 1.0000001 ** 2147483647, 2147483647)
    print(f"✓ (1.0000001, 2147483647) 用了 {elapsed * 1e6:.0f} 微秒"
          f"（朴素版要做 21 亿次乘法）")

    # ! 随机对拍：两种 O(log n) 实现 vs Python 自带的 x ** n
    random.seed(50)
    for _ in range(20000):
        x = random.choice([
            random.uniform(-3, 3),
            random.uniform(-1, 1),
            random.choice([0.0, 1.0, -1.0, 2.0, 0.5]),
        ])
        n = random.choice([
            random.randint(-20, 20),
            random.randint(-1000, 1000),
            random.choice([0, 1, -1, 31, -31]),
        ])
        if x == 0.0 and n < 0:               # ! 题目约束保证不出现，跳过
            continue
        if x != 0.0 and abs(x) != 1.0 and abs(n * math.log10(abs(x))) > 250:
            continue                         # ! 结果超出 double 范围（x ** n 会 OverflowError）
        want = x ** n
        for cls in IMPLS:
            got = cls().myPow(x, n)
            assert close(got, want, n), (cls.__name__, x, n, got, want)

    # ! 迁移示例的对拍：和 Python 内置的 pow(a, b, m) 必须一致
    for _ in range(5000):
        a, e, m = random.randint(0, 10 ** 6), random.randint(0, 10 ** 6), random.randint(1, 10 ** 9)
        assert _pow_mod(a, e, m) == pow(a, e, m)

    print("两种 O(log n) 实现 + 朴素版 + 模幂骨架：10 组守卫 + 25000 组随机对拍全部一致 ✓")
    print("myPow(2.0, 10)  =", Solution_2().myPow(2.0, 10))
    print("myPow(2.0, -2)  =", Solution_2().myPow(2.0, -2))
    print("myPow(2.0, 0)   =", Solution_2().myPow(2.0, 0))
