"""LC-0149 - Max Points on a Line     ★ 第二轮审核新增（填补「斜率归一化 + 共线计数」缺口）

Level 1 · 04 坐标几何与空间计数 —— **Slope Normalization + GCD（不用浮点！）**
题目在问：平面上 `n` 个点，求**同一条直线上**最多有多少个点。

### 决定性观察：枚举「基准点」，而不是枚举「直线」

直线有无穷多条，但**任何一条包含 ≥ 2 个点的直线，一定过某两个点**。
所以：

```
for 每个基准点 i:
    统计从 i 出发到其余所有点的「方向」，用 Hash Map 计数
    出现次数最多的那个方向 k ⟹ 该直线上有 k + 1 个点（+1 是基准点自己）
```

**为什么这样不会漏？** 设最优直线 `L` 上有 `m >= 2` 个点。
当外层循环枚举到 `L` 上任意一个点 `i` 时，`L` 上其余 `m-1` 个点
相对 `i` 的方向**完全相同** ⟹ 它们落进同一个桶 ⟹ 该桶计数 `m-1`
⟹ 答案 `(m-1) + 1 = m`。∎

**为什么只需要「方向」而不需要截距？** 因为所有向量都是**从同一个基准点 `i` 出发**的
—— 过定点 + 定方向 = 唯一一条直线。截距是多余信息。

复杂度 **O(n²)** 时间（n 个基准点 × 每个 O(n) 统计）、O(n) 空间。
`n <= 300`，完全够用。

---

## ⚠️ 核心坑：**不要用浮点斜率**

最容易想到的是 `slope = (y2-y1) / (x2-x1)`，但这有两个致命问题：

1. **垂直线除零**：`x2 == x1` 时直接崩，得单独处理 `inf`。
2. **浮点精度**：两条数学上不同的直线可能算出**同一个 float**，或者
   数学上相同的斜率算出**两个不同的 float**。
   例如 `(0,0)→(1,3)` 和 `(0,0)→(100000,300000)` 斜率都是 3，浮点一般没问题；
   但在坐标范围更大、或斜率是 `1/3` 这类无限小数时，
   `1/3` 的浮点表示会因为约简路径不同而产生最后一位的差异。
   **面试里只要你写了 float 斜率，面试官就会追问精度。**

**正确做法：用「约简后的整数方向向量」作为 Hash Map 的 key。**

```python
dx, dy = x2 - x1, y2 - y1
g = gcd(abs(dx), abs(dy))           # ! math.gcd 接受非负数
dx, dy = dx // g, dy // g           # ! 约简到最简比
```

### 归一化还差一步：**方向相反必须视为同向**

`(1, 2)` 和 `(-1, -2)` 是同一条直线的两个方向！
不统一符号的话，基准点两侧的点会被分进**两个不同的桶** ⟹ 答案偏小。

**反例**：点集 `[(0,0), (1,1), (-1,-1)]` ——
以 `(0,0)` 为基准，`(1,1)` 给方向 `(1,1)`，`(-1,-1)` 给方向 `(-1,-1)`。
不归一化 ⟹ 两个桶各 1 ⟹ 答案 2。**正确答案是 3**（三点共线）。

**统一符号的规则**（本文件采用）：
```python
if dx < 0 or (dx == 0 and dy < 0):
    dx, dy = -dx, -dy
```
- `dx > 0` ⟹ 不动
- `dx < 0` ⟹ 整体取反，让 `dx > 0`
- `dx == 0`（垂直线）⟹ 让 `dy > 0`，统一成 `(0, 1)`

这样每条直线的方向有**唯一**的规范表示：
水平线 → `(1, 0)`；垂直线 → `(0, 1)`；斜率 `2/3` → `(3, 2)`。

### 三种特殊情况如何被自然处理

| 情况 | 归一化后的 key | 要不要特判 |
|---|---|---|
| 垂直线（`dx == 0`） | `(0, 1)` | ❌ 不用 —— gcd 和符号规则自动搞定 |
| 水平线（`dy == 0`） | `(1, 0)` | ❌ 不用 |
| **重合点**（`dx == dy == 0`） | — | ⚠️ **要** —— `gcd(0,0) == 0` 会除零 |

题目**保证所有点互不相同**，所以重合点不会出现。
但 `Solution_2` 仍然显式处理了它（`duplicates` 计数），
这样同一份代码能用在「允许重复点」的变体上 —— 这是常见的面试追问。

---

## 为什么不用「三点共线的叉积判定」？

判断三点共线有个更漂亮的公式（**不需要除法，也不需要 gcd**）：

```python
(y2 - y1) * (x3 - x1) == (y3 - y1) * (x2 - x1)      # ! 叉积为 0 ⟺ 共线
```

但如果用它枚举**所有三元组**就是 **O(n³)**，`n = 300` 时 2700 万次 —— 边界上会超时。
它的正确用法是**验证**（见 `Solution_3` 的暴力基准），不是主算法。
> **记忆点**：叉积判共线（O(1) 判 3 点）和方向哈希（O(n²) 求最大集合）
> 是两个不同场景的工具，不要互相替代。

---

复杂度：解法 1、2 **O(n²)** 时间 / O(n) 空间；解法 3（叉积暴力）**O(n³)**。

边界：
  - `n == 1` → `1`（一个点自己算一条「直线」）
  - `n == 2` → `2`（任意两点必共线）
  - 全部共线 → `n`
  - **垂直线** `[(1,1),(1,2),(1,3)]` → `3`
  - **水平线** `[(1,1),(2,1),(3,1)]` → `3`
  - **基准点在中间**（方向相反）`[(0,0),(1,1),(-1,-1)]` → `3`
  - 负坐标 / 跨象限
  - 没有任何三点共线 → `2`
"""

from collections import defaultdict
from math import gcd
from typing import List


##################################################################################################
##### ! Solution 1: 枚举基准点 + gcd 约简的整数方向向量作为 Hash key（符号统一）
##### ! 时间复杂度: O(n^2 log V)   空间复杂度: O(n)   log V 来自 gcd
##### ! 适用：所有「最多共线点 / 同方向计数」问题。全整数运算，零浮点误差
##### ! ⭐️⭐️⭐️⭐️⭐️ Preferred Solution
##################################################################################################


class Solution_1:
    def maxPoints(self, points: List[List[int]]) -> int:
        n = len(points)
        if n <= 2:
            return n                                # ! 任意两点必共线
        best = 2
        for i in range(n):
            x1, y1 = points[i]
            dirs = defaultdict(int)
            for j in range(i + 1, n):               # ! 只看 i 之后的点就够（见下方说明）
                dx, dy = points[j][0] - x1, points[j][1] - y1
                g = gcd(abs(dx), abs(dy))           # ! 约简到最简整数比
                dx, dy = dx // g, dy // g
                # ! 统一符号：让 (-1,-2) 和 (1,2) 落进同一个桶
                if dx < 0 or (dx == 0 and dy < 0):
                    dx, dy = -dx, -dy
                dirs[(dx, dy)] += 1
                best = max(best, dirs[(dx, dy)] + 1)   # ! +1 是基准点 i 自己
        return best
        # ! 为什么内层从 i+1 开始就不会漏？
        #   任何一条有 m 个点的直线，当外层枚举到它上面「下标最小」的那个点时，
        #   其余 m-1 个点的下标都更大 ⟹ 全部会被 j 扫到 ⟹ 该直线被完整统计一次。


##################################################################################################
##### ! Solution 2: 同上，但显式处理重合点（为「允许重复点」的变体准备）
##### ! 时间复杂度: O(n^2 log V)   空间复杂度: O(n)
##### ! 适用：面试追问「如果点可以重复呢？」时的答案；本题保证点互不相同
##################################################################################################


class Solution_2:
    def maxPoints(self, points: List[List[int]]) -> int:
        n = len(points)
        if n <= 2:
            return n
        best = 1
        for i in range(n):
            x1, y1 = points[i]
            dirs = defaultdict(int)
            duplicates = 0                          # ! 和基准点完全重合的点数
            local = 0
            for j in range(n):
                if j == i:
                    continue
                dx, dy = points[j][0] - x1, points[j][1] - y1
                if dx == 0 and dy == 0:
                    duplicates += 1                 # ! gcd(0,0)==0 会除零 ⟹ 必须先拦下
                    continue
                g = gcd(abs(dx), abs(dy))
                dx, dy = dx // g, dy // g
                if dx < 0 or (dx == 0 and dy < 0):
                    dx, dy = -dx, -dy
                dirs[(dx, dy)] += 1
                local = max(local, dirs[(dx, dy)])
            # ! 重合点在任何一条过基准点的直线上，所以无条件加进来
            best = max(best, local + duplicates + 1)
        return best


##################################################################################################
##### ! Solution 3: 叉积暴力基准（枚举点对定直线，再数有多少点共线）
##### ! 时间复杂度: O(n^3)   空间复杂度: O(1)
##### ! 适用：仅用于对拍。叉积判共线不需要除法、不需要 gcd，但枚举代价是 O(n^3)
##################################################################################################


class Solution_3:
    def maxPoints(self, points: List[List[int]]) -> int:
        n = len(points)
        if n <= 2:
            return n
        best = 2
        for i in range(n):
            for j in range(i + 1, n):
                x1, y1 = points[i]
                x2, y2 = points[j]
                cnt = 0
                for k in range(n):
                    x3, y3 = points[k]
                    # ! 叉积为 0 ⟺ 三点共线（纯整数，无除法无精度问题）
                    if (y2 - y1) * (x3 - x1) == (y3 - y1) * (x2 - x1):
                        cnt += 1
                best = max(best, cnt)
        return best


if __name__ == "__main__":
    import random

    for cls in (Solution_1, Solution_2, Solution_3):
        s = cls()
        assert s.maxPoints([[1, 1], [2, 2], [3, 3]]) == 3
        assert s.maxPoints([[1, 1], [3, 2], [5, 3], [4, 1], [2, 3], [1, 4]]) == 4
        assert s.maxPoints([[0, 0]]) == 1
        assert s.maxPoints([[0, 0], [5, 7]]) == 2
        assert s.maxPoints([[1, 1], [1, 2], [1, 3]]) == 3           # ! 垂直线
        assert s.maxPoints([[1, 1], [2, 1], [3, 1]]) == 3           # ! 水平线
        assert s.maxPoints([[0, 0], [1, 1], [-1, -1]]) == 3         # ! 基准点在中间（方向相反）
        assert s.maxPoints([[0, 0], [1, 0], [0, 1]]) == 2           # ! 无三点共线
        assert s.maxPoints([[-4, -7], [-2, -6], [0, -5], [2, -4]]) == 4   # ! 负坐标全共线

    print("[[1,1],[3,2],[5,3],[4,1],[2,3],[1,4]] ->",
          Solution_1().maxPoints([[1, 1], [3, 2], [5, 3], [4, 1], [2, 3], [1, 4]]))
    print("[[0,0],[1,1],[-1,-1]] ->", Solution_1().maxPoints([[0, 0], [1, 1], [-1, -1]]))

    for _ in range(600):                            # ! 随机对拍（小坐标域 ⟹ 刻意制造共线）
        k = random.randint(1, 8)
        pts = set()
        while len(pts) < k:
            pts.add((random.randint(-4, 4), random.randint(-4, 4)))
        pts = [list(p) for p in pts]
        a = Solution_1().maxPoints([p[:] for p in pts])
        b = Solution_2().maxPoints([p[:] for p in pts])
        c = Solution_3().maxPoints([p[:] for p in pts])
        assert a == b == c, (pts, a, b, c)
    print("随机对拍 600 组通过 ✓（gcd 方向哈希 == 含重合点版 == 叉积 O(n^3) 暴力）")
